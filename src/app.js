import express from 'express';
import cors from 'cors';
import mongoose from 'mongoose';
import eventRoutes from './routes/eventRoutes.js';
import sensorRoutes from './routes/sensorRoutes.js';
import dashboardRoutes from './routes/dashboardRoutes.js';
import {notFound,errorHandler} from './middleware/errorHandler.js';
const app=express();
app.disable('x-powered-by');
const origins=(process.env.CORS_ORIGINS||'http://localhost:5173').split(',').map(x=>x.trim()).filter(Boolean);
app.use(cors({origin(origin,callback){if(!origin||origins.includes(origin))return callback(null,true);callback(new Error('CORS origin denied'));}}));
app.use(express.json({limit:'32kb'}));
app.get('/',(_req,res)=>res.json({service:'AEGIS-X API',status:'online'}));
app.get('/api/health',(_req,res)=>res.json({ok:mongoose.connection.readyState===1,time:new Date().toISOString()}));
app.use('/api/events',eventRoutes);
app.use('/api/readings',sensorRoutes);
app.use('/api/dashboard',dashboardRoutes);
app.use(notFound);
app.use(errorHandler);
export default app;
